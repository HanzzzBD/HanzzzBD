/**
 * README validator (readme-layout §1, §6, §7; PRD §6.16). Checks the whole README:
 * - exactly one START and END marker, on their own lines, in order;
 * - the generated block: every required section marker exactly once, only HTML that GitHub
 *   keeps (allow-listed tags and attributes), links and image sources restricted to
 *   github.com or repository paths, non-empty alt text ≤ 600 characters, balanced
 *   <details>/<picture>/<p>, no leftover placeholders, size ≤ 15 KB, heading order;
 * - optionally, that every referenced repository file exists, and that content outside the
 *   markers is byte-identical to a previous version.
 * A README whose block is still empty ("pending": before the first real run) is valid in
 * pending mode only.
 */
import { END, findMarkers, MarkerError, outsideMarkers, START } from "./inject.ts";
import type { SectionId } from "./model.ts";

export interface ReadmeIssue {
  code: string;
  detail: string;
}

export interface ReadmeRules {
  /** "generated": the block must hold every required section. "pending": an empty block is allowed. */
  mode: "generated" | "pending";
  requiredSections: readonly SectionId[];
  maxBlockBytes?: number;
  /** Returns true when a repository-relative path exists (assets, docs pages). */
  fileExists?: (path: string) => boolean;
  /** Previous README: content outside the markers must be byte-identical. */
  previous?: string;
}

const ALLOWED_TAGS: Readonly<Record<string, readonly string[]>> = {
  p: ["align"],
  div: ["align"],
  a: ["href"],
  img: ["src", "width", "alt"],
  picture: [],
  source: ["media", "srcset"],
  details: [],
  summary: [],
  sub: [],
  sup: [],
  b: [],
  strong: [],
  i: [],
  em: [],
  br: [],
  code: [],
};
const VOID = new Set(["img", "source", "br"]);
const BALANCED = ["details", "summary", "picture", "p", "a", "sub", "b"];
const GITHUB_URL =
  /^https:\/\/github\.com\/[A-Za-z0-9](?:[A-Za-z0-9]|-(?=[A-Za-z0-9])){0,38}(?:\/[A-Za-z0-9._-]{1,100})?(?:\/(?:pull|issues|releases\/tag)\/[A-Za-z0-9._-]+)?$/;
const REPO_PATH = /^(?:[a-z0-9][a-z0-9_-]*\/)*[a-z0-9][a-z0-9_.-]*\.(?:md|svg)(?:#[a-z0-9-]+)?$/;
const MEDIA = /^\(prefers-color-scheme: (?:dark|light)\)$/;

function urlIssue(url: string): string | null {
  if (GITHUB_URL.test(url)) return null;
  if (REPO_PATH.test(url) && !url.includes("..")) return null;
  return `unsafe or unexpected URL "${url.slice(0, 60)}"`;
}

const decode = (v: string) =>
  v
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");

export function validateReadme(readme: string, rules: ReadmeRules): ReadmeIssue[] {
  const issues: ReadmeIssue[] = [];
  const add = (code: string, detail: string) => issues.push({ code, detail });
  let block: string;
  try {
    const span = findMarkers(readme);
    block = readme.slice(span.start, span.end);
  } catch (error) {
    add("markers", error instanceof MarkerError ? error.message : "marker error");
    return issues;
  }
  if (rules.previous !== undefined) {
    try {
      if (outsideMarkers(rules.previous) !== outsideMarkers(readme))
        add("outside_changed", "content outside the markers changed");
    } catch {
      add("markers", "previous README has invalid markers");
    }
  }

  const max = rules.maxBlockBytes ?? 15_000;
  const bytes = Buffer.byteLength(block, "utf8");
  if (bytes > max) add("size_budget", `block is ${bytes} bytes (> ${max})`);

  const withoutComments = block.replace(/<!--[\s\S]*?-->/g, "");
  if (rules.mode === "pending" && withoutComments.trim() === "") return issues;

  // Required sections.
  const markers = [...block.matchAll(/<!-- legends:section:([a-z-]+) -->/g)].map((m) => m[1] ?? "");
  for (const id of rules.requiredSections) {
    const n = markers.filter((m) => m === id).length;
    if (n !== 1)
      add("section", n === 0 ? `missing section "${id}"` : `section "${id}" appears ${n} times`);
  }
  if (!/^<!-- Generated by GitHub Legends/.test(block.trimStart()))
    add("generator_comment", "the block must start with the generator comment");
  if (/\{\{|\}\}/.test(withoutComments)) add("placeholder", "unreplaced template placeholder");
  if (block.includes(START) || block.includes(END)) add("markers", "nested marker");

  // HTML: allow-listed tags and attributes only.
  const stack: string[] = [];
  for (const match of withoutComments.matchAll(
    /<(\/?)([a-zA-Z][a-zA-Z0-9-]*)((?:\s+[^\s=>]+(?:="[^"]*")?)*)\s*(\/?)>/g,
  )) {
    const [, closing, rawTag, attrText] = match;
    const tag = (rawTag ?? "").toLowerCase();
    const allowed = ALLOWED_TAGS[tag];
    if (!allowed) {
      add("html_tag", `<${tag}> is not allowed`);
      continue;
    }
    if (closing) {
      if (BALANCED.includes(tag)) {
        if (stack.at(-1) !== tag) add("unbalanced", `unexpected </${tag}>`);
        else stack.pop();
      }
      continue;
    }
    const attrs = [...(attrText ?? "").matchAll(/([^\s=>]+)(?:="([^"]*)")?/g)].map(
      (a) => [a[1] ?? "", decode(a[2] ?? "")] as const,
    );
    for (const [name, value] of attrs) {
      if (!allowed.includes(name)) add("html_attribute", `${tag}@${name} is not allowed`);
      if (name === "href" || name === "src" || name === "srcset") {
        const problem = urlIssue(value);
        if (problem) add("url", `${tag}@${name}: ${problem}`);
        else if (
          !value.startsWith("https://") &&
          rules.fileExists &&
          !rules.fileExists(value.split("#")[0] ?? value)
        )
          add("missing_file", `${tag}@${name} → ${value}`);
      }
      if (name === "media" && !MEDIA.test(value))
        add("html_attribute", `unexpected media query "${value}"`);
      if (name === "width" && !/^\d{1,3}$/.test(value))
        add("html_attribute", `invalid width "${value}"`);
    }
    if (tag === "img") {
      const alt = attrs.find(([n]) => n === "alt")?.[1];
      if (!alt || alt.trim() === "") add("alt", "image without alt text");
      else if (alt.length > 600) add("alt", `alt text is ${alt.length} characters (> 600)`);
    }
    if (BALANCED.includes(tag) && !VOID.has(tag)) stack.push(tag);
  }
  if (stack.length > 0) add("unbalanced", `unclosed <${stack.join(">, <")}>`);

  // Markdown links: only GitHub URLs or repository paths.
  for (const m of withoutComments.matchAll(/(?<!\\)\]\(([^)\s]+)\)/g)) {
    const url = m[1] ?? "";
    const problem = urlIssue(url);
    if (problem) add("url", `link: ${problem}`);
    else if (
      !url.startsWith("https://") &&
      rules.fileExists &&
      !rules.fileExists(url.split("#")[0] ?? url)
    )
      add("missing_file", `link → ${url}`);
  }
  // URL attributes are checked above; this also catches unquoted or malformed ones the tag scan skips.
  if (/(?:href|src|srcset)\s*=\s*["']?\s*(?:javascript|data|vbscript):/i.test(withoutComments))
    add("url", "script or data URL");

  // Markdown inside HTML blocks needs a blank line after </summary> (readme-layout §3).
  for (const m of withoutComments.matchAll(/<\/summary>\n(?!\n)/g))
    add("blank_line", `missing blank line after </summary> at ${m.index}`);

  // Heading order inside the block: no jumps of more than one level.
  let previous = 0;
  for (const m of withoutComments.matchAll(/^(#{1,6}) /gm)) {
    const level = m[1]?.length ?? 0;
    if (previous > 0 && level > previous + 1)
      add("heading_order", `heading level ${level} after ${previous}`);
    previous = level;
  }
  return issues;
}

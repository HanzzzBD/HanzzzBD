/**
 * Generates the README example (SAMPLE DATA) under preview/readme/:
 * - README.md: the real profile README with the sample block injected (outside content
 *   unchanged), so GitHub renders it with working relative images;
 * - block.md: the generated block alone;
 * - assets/legends/{dark,light}/*.svg: every card the block references;
 * - validation.md: README and asset validation results;
 * - approx.html: an approximate local rendering for visual inspection (not GitHub's renderer).
 * Usage: node scripts/preview-readme.ts
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { injectBlock } from "../src/render/readme/inject.ts";
import { buildProfileModel, SECTION_IDS } from "../src/render/readme/model.ts";
import { renderProfile, validateProfileAssets } from "../src/render/readme/render.ts";
import { validateReadme } from "../src/render/readme/validate.ts";
import { sampleProfileInput } from "../test/fixtures/profile-sample.ts";

const legends = fileURLToPath(new URL("../", import.meta.url));
const repoRoot = join(legends, "..");
const out = join(legends, "preview/readme");
mkdirSync(out, { recursive: true });

const model = buildProfileModel(sampleProfileInput());
const template = readFileSync(join(legends, "templates/readme-block.md"), "utf8");
const { block, files } = renderProfile(model, template);
for (const [path, svg] of files) {
  mkdirSync(dirname(join(out, path)), { recursive: true });
  writeFileSync(join(out, path), svg);
}
const original = readFileSync(join(repoRoot, "README.md"), "utf8");
const readme = injectBlock(original, block);
writeFileSync(join(out, "README.md"), readme);
writeFileSync(join(out, "block.md"), block);
// The footer links to docs/legends/how-it-works.md; mirror it so the preview's link resolves.
mkdirSync(join(out, "docs/legends"), { recursive: true });
writeFileSync(
  join(out, "docs/legends/how-it-works.md"),
  readFileSync(join(repoRoot, "docs/legends/how-it-works.md"), "utf8"),
);

const readmeIssues = validateReadme(readme, {
  mode: "generated",
  requiredSections: SECTION_IDS,
  previous: original,
  fileExists: (p) => existsSync(join(out, p)),
});
const assetIssues = validateProfileAssets(model, files);
const sizes = [...files].map(([p, s]) => `- \`${p}\`: ${Buffer.byteLength(s)} bytes`);
const report = [
  "# README preview: validation report",
  "",
  "SAMPLE DATA. Generated by `node scripts/preview-readme.ts`.",
  "",
  `- Block: ${Buffer.byteLength(block)} bytes (budget 15,000)`,
  `- README issues: ${readmeIssues.length === 0 ? "none" : readmeIssues.map((i) => `${i.code} (${i.detail})`).join("; ")}`,
  `- Asset issues: ${assetIssues.length === 0 ? "none" : assetIssues.map((i) => `${i.file}: ${i.code} (${i.detail})`).join("; ")}`,
  "",
  "## Assets",
  "",
  ...sizes,
];
writeFileSync(join(out, "validation.md"), `${report.join("\n")}\n`);
writeFileSync(join(out, "approx.html"), approximateHtml(block));
process.stdout.write(`${report.join("\n")}\n`);
if (readmeIssues.length + assetIssues.length > 0) process.exitCode = 1;

/**
 * Very small Markdown-to-HTML approximation for local screenshots only: headings, paragraphs,
 * task lists, lists, tables, blockquotes, bold/italic/strike/links; HTML passes through.
 * It is NOT GitHub's renderer and is never used for the real README.
 */
function approximateHtml(markdown: string): string {
  const inline = (s: string) =>
    s
      .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
      .replace(/~~([^~]+)~~/g, "<del>$1</del>")
      .replace(/(^|[^\\])\*([^*]+)\*/g, "$1<em>$2</em>")
      .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')
      .replace(/\\([\\`*_[\]{}()#+!|~])/g, "$1");
  const lines = markdown.replace(/<!--[\s\S]*?-->/g, "").split("\n");
  const html: string[] = [];
  let i = 0;
  while (i < lines.length) {
    const l = lines[i] ?? "";
    if (l.trim() === "") {
      i++;
      continue;
    }
    const heading = /^(#{1,6}) (.*)$/.exec(l);
    if (heading) {
      html.push(`<h${heading[1]?.length}>${inline(heading[2] ?? "")}</h${heading[1]?.length}>`);
      i++;
    } else if (l.startsWith("|")) {
      const rows: string[] = [];
      while ((lines[i] ?? "").startsWith("|")) rows.push(lines[i++] ?? "");
      const cells = (r: string) =>
        r
          .slice(1, -1)
          .split(/(?<!\\)\|/)
          .map((c) => inline(c.trim()));
      html.push(
        `<table><tr>${cells(rows[0] ?? "")
          .map((c) => `<th>${c}</th>`)
          .join("")}</tr>${rows
          .slice(2)
          .map(
            (r) =>
              `<tr>${cells(r)
                .map((c) => `<td>${c}</td>`)
                .join("")}</tr>`,
          )
          .join("")}</table>`,
      );
    } else if (l.startsWith("- ")) {
      const items: string[] = [];
      while ((lines[i] ?? "").startsWith("- ")) items.push(lines[i++] ?? "");
      html.push(
        `<ul>${items
          .map(
            (it) =>
              `<li>${inline(
                it
                  .slice(2)
                  .replace(/^\[x\] /, "☑ ")
                  .replace(/^\[ \] /, "☐ "),
              )}</li>`,
          )
          .join("")}</ul>`,
      );
    } else if (l.startsWith("> ")) {
      const quote: string[] = [];
      while ((lines[i] ?? "").startsWith(">")) quote.push((lines[i++] ?? "").replace(/^> ?/, ""));
      html.push(`<blockquote>${inline(quote.join(" "))}</blockquote>`);
    } else if (/^\s*</.test(l)) {
      html.push(inline(l));
      i++;
    } else {
      const para: string[] = [];
      while ((lines[i] ?? "").trim() !== "" && !/^(#|\||- |> |\s*<)/.test(lines[i] ?? ""))
        para.push(lines[i++] ?? "");
      html.push(`<p>${inline(para.join(" "))}</p>`);
    }
  }
  return `<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>README block (approximation)</title>
<style>body{margin:0;background:#0d1117;color:#e6edf3;font:16px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif}
main{max-width:830px;margin:0 auto;padding:24px 16px}img{max-width:100%;height:auto;vertical-align:middle}a{color:#4493f8}
table{border-collapse:collapse;display:block;overflow:auto}td,th{border:1px solid #3d444d;padding:6px 13px}
blockquote{border-left:4px solid #3d444d;margin:0;padding:0 16px;color:#9198a1}details{margin:16px 0}summary{cursor:pointer}
ul{padding-left:2em}sub{font-size:75%}</style><main>${html.join("\n")}</main>\n`;
}

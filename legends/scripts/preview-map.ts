/**
 * Generates the world-map preview set (SAMPLE DATA) under preview/world-map/:
 * dark and light SVGs per scenario, the README block with the text fallback, a validation
 * report, and an HTML harness that shows each map at desktop (420 px) and phone (360 px)
 * column widths. Usage: node scripts/preview-map.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { runEngine } from "../src/engine/engine.ts";
import { mapEmbed, renderMap } from "../src/render/map/index.ts";
import { buildMapState, type MapFacts, mapStateFromFacts } from "../src/render/map/state.ts";
import { THEMES } from "../src/render/tokens.ts";
import { overlapIssues, validateSvg } from "../src/render/validate.ts";
import {
  LEGEND,
  LONG_NAME,
  MID_JOURNEY,
  NEW_PLAYER,
  THRONE_CURRENT,
  UNICODE_NAME,
} from "../test/fixtures/map-facts.ts";
import {
  CONFIG,
  commitsOn,
  HUMAN,
  OWN,
  pr,
  review,
  snapshot,
  wib,
} from "../test/helpers/events.ts";

const out = fileURLToPath(new URL("../preview/world-map/", import.meta.url));
mkdirSync(out, { recursive: true });

/** One real engine run over synthetic activity (5 weeks), to show the full pipeline. */
function fromEngine() {
  const events = [
    snapshot(OWN, "2026-10-01", { TypeScript: 7000, Python: 3000 }),
    ...Array.from({ length: 30 }, (_, i) =>
      commitsOn(
        `2026-10-${String(1 + i).padStart(2, "0")}`,
        6,
        {},
        `${String(8 + (i % 9)).padStart(2, "0")}:10`,
      ),
    ).flat(),
    pr({ id: "P1", mergedAt: wib("2026-10-08", "20:00") }),
    review({ at: wib("2026-10-09", "20:00"), prAuthor: HUMAN(2001) }),
  ];
  const output = runEngine({
    config: CONFIG,
    events,
    ledger: [],
    runAt: "2026-11-01T00:00:00Z",
    closureAllowed: true,
  });
  return buildMapState(output, { name: "Sample Player", sample: true });
}

const facts = (f: MapFacts, name: string, extra: { stale?: boolean } = {}) =>
  mapStateFromFacts(f, { name, sample: true, ...extra });

const scenarios = {
  "from-engine": fromEngine(),
  "new-player": facts(NEW_PLAYER, "Sample Player"),
  "mid-journey": facts(MID_JOURNEY, "Ayu Lestari"),
  "throne-current": facts(THRONE_CURRENT, UNICODE_NAME),
  "legend-long-name": facts(LEGEND, LONG_NAME, { stale: true }),
};

const report: string[] = [
  "# World map preview: validation report",
  "",
  "SAMPLE DATA. Generated by `node scripts/preview-map.ts`.",
  "",
];
const harness: string[] = [];
for (const [name, state] of Object.entries(scenarios)) {
  for (const theme of Object.values(THEMES)) {
    const { svg, boxes } = renderMap(state, theme);
    const file = `${name}.${theme.id}.svg`;
    writeFileSync(`${out}${file}`, svg);
    const issues = [
      ...validateSvg(svg, { theme, width: 420, height: 820, maxBytes: 100_000 }),
      ...overlapIssues(boxes),
    ];
    report.push(
      `- \`${file}\`: ${Buffer.byteLength(svg)} bytes, ${issues.length === 0 ? "no issues" : issues.map((i) => `${i.code} (${i.detail})`).join("; ")}`,
    );
  }
  writeFileSync(
    `${out}${name}.md`,
    `${mapEmbed(state, { dark: `${name}.dark.svg`, light: `${name}.light.svg` })}\n`,
  );
  harness.push(
    `<section><h2>${name}</h2><div class="row">` +
      ["dark", "light"]
        .map(
          (t) =>
            `<figure><img src="${name}.${t}.svg" width="420"><figcaption>${t} · 420 px</figcaption></figure><figure class="phone"><img src="${name}.${t}.svg"><figcaption>${t} · 360 px</figcaption></figure>`,
        )
        .join("") +
      "</div></section>",
  );
}
writeFileSync(`${out}validation.md`, `${report.join("\n")}\n`);
writeFileSync(
  `${out}index.html`,
  `<!doctype html><meta charset="utf-8"><title>World map preview</title><style>body{margin:16px;background:#888;font:14px sans-serif}.row{display:flex;gap:16px;flex-wrap:wrap}figure{margin:0}.phone{width:360px}.phone img{width:100%}</style>${harness.join("")}\n`,
);
process.stdout.write(`${report.join("\n")}\n`);
